// Package codegen emits C++ service bindings without requiring Go-specific proto options.
package codegen

import (
	"crypto/sha256"
	"fmt"
	"path"
	"slices"
	"strings"

	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protodesc"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

// Generate produces source-relative C++ headers and implementations for all RPC shapes.
func Generate(request *pluginpb.CodeGeneratorRequest) (*pluginpb.CodeGeneratorResponse, error) {
	if request.GetParameter() != "" && request.GetParameter() != "paths=source_relative" {
		return nil, fmt.Errorf("unsupported parameter %q", request.GetParameter())
	}
	// Service bindings delegate all field-level Edition features to protoc's
	// C++ message generator. Bound descriptor resolution to the tested range.
	for _, file := range request.GetProtoFile() {
		if file.GetSyntax() == "editions" && (file.GetEdition() < descriptorpb.Edition_EDITION_2023 || file.GetEdition() > descriptorpb.Edition_EDITION_2024) {
			return nil, fmt.Errorf("%s: unsupported edition %s (supported: 2023–2024)", file.GetName(), file.GetEdition())
		}
	}
	files, err := protodesc.NewFiles(&descriptorpb.FileDescriptorSet{File: request.GetProtoFile()})
	if err != nil {
		return nil, fmt.Errorf("resolve descriptors: %w", err)
	}
	response := &pluginpb.CodeGeneratorResponse{
		SupportedFeatures: proto.Uint64(uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL | pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)),
		MinimumEdition:    proto.Int32(int32(descriptorpb.Edition_EDITION_2023)),
		MaximumEdition:    proto.Int32(int32(descriptorpb.Edition_EDITION_2024)),
	}
	seen := make(map[string]bool)
	for _, filename := range request.GetFileToGenerate() {
		if seen[filename] {
			return nil, fmt.Errorf("duplicate input %q", filename)
		}
		seen[filename] = true
		if !safePath(filename) {
			return nil, fmt.Errorf("invalid proto path %q", filename)
		}
		file, err := files.FindFileByPath(filename)
		if err != nil {
			return nil, fmt.Errorf("find %q: %w", filename, err)
		}
		if file.Services().Len() == 0 {
			continue
		}
		header, source, err := generateFile(file)
		if err != nil {
			return nil, err
		}
		base := strings.TrimSuffix(filename, ".proto")
		response.File = append(response.File,
			&pluginpb.CodeGeneratorResponse_File{Name: proto.String(base + ".connect.h"), Content: proto.String(header)},
			&pluginpb.CodeGeneratorResponse_File{Name: proto.String(base + ".connect.cc"), Content: proto.String(source)})
	}
	return response, nil
}

func safePath(filename string) bool {
	if filename == "" || path.IsAbs(filename) || path.Clean(filename) != filename || strings.HasPrefix(filename, "../") || !strings.HasSuffix(filename, ".proto") {
		return false
	}
	for _, c := range filename {
		if !((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || strings.ContainsRune("_-./", c)) {
			return false
		}
	}
	return true
}

func generateFile(file protoreflect.FileDescriptor) (string, string, error) {
	base := strings.TrimSuffix(file.Path(), ".proto")
	guard := "CONNECTCPP_GENERATED_" + strings.ToUpper(strings.NewReplacer("/", "_", ".", "_", "-", "_").Replace(base)) + "_CONNECT_H_"
	digest := sha256.Sum256([]byte(file.Path()))
	guard += fmt.Sprintf("%X_", digest[:8])
	namespace := "connectrpc::generated"
	if file.Package() != "" {
		namespace += "::" + cppNamespace(file.Package())
	}
	var header, source strings.Builder
	fmt.Fprintf(&header, "// Generated by protoc-gen-connect-cpp. DO NOT EDIT.\n#ifndef %s\n#define %s\n\n", guard, guard)
	header.WriteString("#include <asio/awaitable.hpp>\n#include <utility>\n#include \"connectrpc/rpc.h\"\n")
	includes := map[string]bool{base + ".pb.h": true}
	for i := 0; i < file.Services().Len(); i++ {
		service := file.Services().Get(i)
		for j := 0; j < service.Methods().Len(); j++ {
			method := service.Methods().Get(j)
			for _, message := range []protoreflect.MessageDescriptor{method.Input(), method.Output()} {
				filename := message.ParentFile().Path()
				if !safePath(filename) {
					return "", "", fmt.Errorf("invalid dependency path %q", filename)
				}
				includes[strings.TrimSuffix(filename, ".proto")+".pb.h"] = true
			}
		}
	}
	paths := make([]string, 0, len(includes))
	for filename := range includes {
		paths = append(paths, filename)
	}
	slices.Sort(paths)
	for _, filename := range paths {
		fmt.Fprintf(&header, "#include %q\n", filename)
	}
	fmt.Fprintf(&header, "\nnamespace %s {\n", namespace)
	fmt.Fprintf(&source, "// Generated by protoc-gen-connect-cpp. DO NOT EDIT.\n#include %q\n\nnamespace %s {\n", base+".connect.h", namespace)
	for i := 0; i < file.Services().Len(); i++ {
		generateService(&header, &source, file.Services().Get(i))
	}
	fmt.Fprintf(&header, "}  // namespace %s\n#endif  // %s\n", namespace, guard)
	fmt.Fprintf(&source, "}  // namespace %s\n", namespace)
	return header.String(), source.String(), nil
}

func generateService(header, source *strings.Builder, service protoreflect.ServiceDescriptor) {
	name := string(service.Name())
	client := name + "Client"
	handler := name + "Handler"
	methods := methodNames(service)
	fmt.Fprintf(header, "// The runtime client must outlive this stub and all calls.\nclass %s {\n public:\n  explicit %s(::connectrpc::Client& client) : client_(client) {}\n", client, client)
	for i := 0; i < service.Methods().Len(); i++ {
		method := service.Methods().Get(i)
		api := describeMethod(method)
		fmt.Fprintf(header, "  ::asio::awaitable<%s> %s(%s%s options = {}) const;\n", api.clientResult, methods[i], api.clientRequest, api.options)
	}
	header.WriteString(" private:\n  ::connectrpc::Client& client_;\n};\n")
	fmt.Fprintf(header, "// Implementations and the server must outlive registered calls.\nclass %s {\n public:\n  virtual ~%s() = default;\n", handler, handler)
	for i := 0; i < service.Methods().Len(); i++ {
		method := service.Methods().Get(i)
		api := describeMethod(method)
		fmt.Fprintf(header, "  virtual ::asio::awaitable<%s> %s(%s) = 0;\n", api.handlerResult, methods[i], api.handlerParams)
	}
	fmt.Fprintf(header, "};\n::connectrpc::Status Register%s(::connectrpc::Server& server, %s& handler);\n", handler, handler)
	for i := 0; i < service.Methods().Len(); i++ {
		method := service.Methods().Get(i)
		input, output := cppMessage(method.Input()), cppMessage(method.Output())
		procedure := "/" + string(service.FullName()) + "/" + string(method.Name())
		api := describeMethod(method)
		fmt.Fprintf(source, "::asio::awaitable<%s> %s::%s(%s%s options) const {\n  return client_.%s<%s, %s>(%q, %sstd::move(options)%s);\n}\n", api.clientResult, client, methods[i], api.clientRequest, api.options, api.runtimeMethod, input, output, procedure, api.clientArgs, api.methodOptions)
	}
	fmt.Fprintf(source, "::connectrpc::Status Register%s(::connectrpc::Server& server, %s& handler) {\n", handler, handler)
	for i := 0; i < service.Methods().Len(); i++ {
		procedure := "/" + string(service.FullName()) + "/" + string(service.Methods().Get(i).Name())
		fmt.Fprintf(source, "  {\n    auto status = server.CanRegister(%q);\n    if (!status.ok()) return status;\n  }\n", procedure)
	}
	for i := 0; i < service.Methods().Len(); i++ {
		method := service.Methods().Get(i)
		input, output := cppMessage(method.Input()), cppMessage(method.Output())
		procedure := "/" + string(service.FullName()) + "/" + string(method.Name())
		api := describeMethod(method)
		fmt.Fprintf(source, "  {\n    auto status = server.Register%s<%s, %s>(%q, [&handler](%s) { return handler.%s(%s); }%s);\n    if (!status.ok()) return status;\n  }\n", api.runtimeMethod, input, output, procedure, api.handlerParams, methods[i], api.handlerArgs, api.methodOptions)
	}
	source.WriteString("  return {};\n}\n")
}

// methodAPI keeps declarations, definitions and registration lambdas in sync.
type methodAPI struct {
	methodOptions string
	runtimeMethod string
	clientResult  string
	clientRequest string
	clientArgs    string
	options       string
	handlerResult string
	handlerParams string
	handlerArgs   string
}

func describeMethod(method protoreflect.MethodDescriptor) methodAPI {
	input, output := cppMessage(method.Input()), cppMessage(method.Output())
	api := methodAPI{
		runtimeMethod: "Unary",
		clientResult:  "::connectrpc::Response<" + output + ">",
		clientRequest: input + " request, ",
		clientArgs:    "std::move(request), ",
		options:       "::connectrpc::CallOptions",
		handlerResult: "::connectrpc::Response<" + output + ">",
		handlerParams: "::connectrpc::Request<" + input + "> request",
		handlerArgs:   "std::move(request)",
	}
	if !method.IsStreamingClient() && !method.IsStreamingServer() {
		switch method.Options().(*descriptorpb.MethodOptions).GetIdempotencyLevel() {
		case descriptorpb.MethodOptions_NO_SIDE_EFFECTS:
			api.methodOptions = ", {::connectrpc::Idempotency::kNoSideEffects}"
		case descriptorpb.MethodOptions_IDEMPOTENT:
			api.methodOptions = ", {::connectrpc::Idempotency::kIdempotent}"
		}
		return api
	}
	api.clientResult = "::connectrpc::Result<::connectrpc::TypedStream<" + input + ", " + output + ">>"
	api.options = "::connectrpc::StreamCallOptions"
	api.runtimeMethod = "ServerStream"
	if method.IsStreamingClient() {
		api.runtimeMethod = "ClientStream"
		api.clientRequest = ""
		api.clientArgs = ""
		api.handlerParams = "::connectrpc::CallContext context"
		api.handlerArgs = "std::move(context)"
	}
	if method.IsStreamingServer() {
		api.handlerResult = "::connectrpc::StreamCompletion"
		if method.IsStreamingClient() {
			api.runtimeMethod = "BidiStream"
		}
	}
	api.handlerParams += ", ::connectrpc::TypedStream<" + output + ", " + input + "> stream"
	api.handlerArgs += ", std::move(stream)"
	return api
}

func methodNames(service protoreflect.ServiceDescriptor) []string {
	used := map[string]bool{string(service.Name()) + "Client": true, string(service.Name()) + "Handler": true, "client_": true}
	result := make([]string, service.Methods().Len())
	for i := range result {
		name := cppIdentifier(string(service.Methods().Get(i).Name()))
		if strings.Contains(name, "__") || strings.HasPrefix(name, "_") {
			name = fmt.Sprintf("Rpc_%x", []byte(name))
		}
		for used[name] {
			name += "Rpc"
		}
		used[name] = true
		result[i] = name
	}
	return result
}

func cppNamespace(pkg protoreflect.FullName) string {
	parts := strings.Split(string(pkg), ".")
	for i, part := range parts {
		parts[i] = cppIdentifier(part)
	}
	return strings.Join(parts, "::")
}

func cppMessage(message protoreflect.MessageDescriptor) string {
	pkg := message.ParentFile().Package()
	name := string(message.FullName())
	if pkg != "" {
		name = strings.TrimPrefix(name, string(pkg)+".")
	}
	name = cppIdentifier(strings.ReplaceAll(name, ".", "_"))
	if pkg != "" {
		return "::" + cppNamespace(pkg) + "::" + name
	}
	return "::" + name
}

func cppIdentifier(name string) string {
	const keywords = " alignas alignof and and_eq asm atomic_cancel atomic_commit atomic_noexcept auto bitand bitor bool break case catch char char8_t char16_t char32_t class compl concept const consteval constexpr constinit const_cast continue co_await co_return co_yield decltype default delete do double dynamic_cast else enum explicit export extern false float for friend goto if inline int long mutable namespace new noexcept not not_eq nullptr operator or or_eq private protected public reflexpr register reinterpret_cast requires return short signed sizeof static static_assert static_cast struct switch synchronized template this thread_local throw true try typedef typeid typename union unsigned using virtual void volatile wchar_t while xor xor_eq "
	if strings.Contains(keywords, " "+name+" ") {
		return name + "_"
	}
	return name
}
